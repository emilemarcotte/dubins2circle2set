def find_circle_intersections(x1, y1, r1, x2, y2, r2):
    """
    Finds the intersection points of two circles. Generated by Gemini.
    Parameters:
        x1, y1, r1: Center (x, y) and radius of the first circle
        x2, y2, r2: Center (x, y) and radius of the second circle

    Returns:
        List of tuples representing the (x, y) intersection points.
        Returns [] if there are no intersections or if circles are identical.
    """
    dx = x2 - x1
    dy = y2 - y1
    d = hypot(dx, dy)

    # Check for no intersection or infinite solutions
    if d > r1 + r2:
        return []  # Circles are too far apart
    if d < abs(r1 - r2):
        return []  # One circle is completely inside the other
    if d == 0 and r1 == r2:
        return []  # Circles are identical (infinite solutions)

    # Distance from center 1 to the line connecting the intersection points (chord line)
    a = (r1**2 - r2**2 + d**2) / (2 * d)

    # Distance from the chord line to the intersection points
    h_sq = r1**2 - a**2
    if h_sq < 0:
        return []
    h = sqrt(h_sq)

    # Midpoint of the chord along the line of centers
    x_mid = x1 + a * dx / d
    y_mid = y1 + a * dy / d

    # Offset vectors perpendicular to the line of centers
    ox = -dy * (h / d)
    oy = dx * (h / d)

    # The two intersection points
    p1 = (x_mid + ox, y_mid + oy)
    p2 = (x_mid - ox, y_mid - oy)

    # If h is 0, the circles are tangent at a single point
    if h == 0:
        return [p1]

    return [p1, p2]

